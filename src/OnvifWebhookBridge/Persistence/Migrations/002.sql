CREATE TABLE Rules (
 Id TEXT PRIMARY KEY NOT NULL, CameraId TEXT NOT NULL REFERENCES Cameras(Id) ON DELETE RESTRICT,
 Name TEXT NOT NULL, Topic TEXT NOT NULL, Section INTEGER, FieldName TEXT, ExpectedValue TEXT, Comparison INTEGER,
 Enabled INTEGER NOT NULL CHECK(Enabled IN (0,1)), Mode INTEGER NOT NULL, CooldownTicks INTEGER NOT NULL,
 Url TEXT NOT NULL, Method TEXT NOT NULL, JsonBody TEXT, AdditionalAttempts INTEGER NOT NULL);
CREATE TABLE Headers (
 RuleId TEXT NOT NULL REFERENCES Rules(Id) ON DELETE CASCADE, Position INTEGER NOT NULL,
 Name TEXT NOT NULL, Value TEXT NOT NULL, PRIMARY KEY(RuleId,Position));
